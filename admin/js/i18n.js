let bahasa = (() => {
  try {
    const disimpan = localStorage.getItem(KUNCI_BAHASA);
    if (disimpan && kamus[disimpan]) return disimpan;
  } catch { /* localStorage bisa dimatikan */ }
  // Ikuti bahasa browser kalau belum pernah memilih. Orang yang membuka
  // dashboard dengan browser berbahasa Inggris kemungkinan besar memang lebih
  // nyaman membacanya dalam bahasa Inggris.
  return String(navigator.language || '').toLowerCase().startsWith('id') ? 'id' : 'en';
})();

export const bahasaAktif = () => bahasa;

export function gantiBahasa(kode) {
  if (!kamus[kode]) return false;
  bahasa = kode;
  try { localStorage.setItem(KUNCI_BAHASA, kode); } catch { /* abaikan */ }
  document.documentElement.lang = kode;
  return true;
}

/**
 * Ambil teks terjemahan. `{nama}` di dalam teks diganti nilai dari `params`.
 *
 * Kunci yang tidak ada dikembalikan apa adanya, bukan diganti string kosong —
 * teks aneh di layar jauh lebih mudah ditemukan daripada ruang kosong.
 */
export function t(kunci, params) {
  // Bentuk tunggal.
  //
  // Bahasa Indonesia tidak membedakan tunggal dan jamak, jadi satu kalimat
  // cukup. Bahasa Inggris membedakannya, dan "1 server errors" terbaca sebagai
  // kesalahan mesin. Kalau ada varian `<kunci>_one` dan n bernilai 1, varian
  // itu yang dipakai — kunci yang tidak butuh pembedaan cukup tidak punya
  // varian, jadi tidak ada beban tambahan untuk mayoritas teks.
  const tunggal = params?.n === 1 || params?.n === '1';
  const kamusAktif = kamus[bahasa];
  const teks =
    (tunggal ? kamusAktif[`${kunci}_one`] : undefined)
    ?? kamusAktif[kunci]
    ?? (tunggal ? kamus.id[`${kunci}_one`] : undefined)
    ?? kamus.id[kunci]
    ?? kunci;
  if (!params) return teks;
  return teks.replace(/\{(\w+)\}/g, (cocok, nama) => (params[nama] ?? cocok));
}

// Format tanggal dan angka mengikuti bahasa yang dipilih, bukan dipaku ke
// satu locale. "22 Agu 2026" dan "22 Aug 2026" adalah hal yang sama, tapi
// yang pertama terlihat salah di antarmuka berbahasa Inggris.
export const localeIntl = () => (bahasa === 'id' ? 'id-ID' : 'en-GB');

document.documentElement.lang = bahasa;
